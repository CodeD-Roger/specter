# Fonction pour détecter le système d'exploitation
detect_os() {
    if [ -f /etc/os-release ]; then
        . /etc/os-release
        OS=$NAME
        echo -e "${CYAN}Système d'exploitation détecté : $OS${NC}"
    else
        echo -e "${RED}Impossible de détecter le système d'exploitation${NC}"
        exit 1
    fi
}

