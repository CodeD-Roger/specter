        echo -e "${YELLOW}Installation de wkhtmltopdf...${NC}"
        apt-get install -y wkhtmltopdf
    fi

    # Vérifier et installer whois si nécessaire
    if ! command -v whois &> /dev/null; then
        echo -e "${YELLOW}Installation de whois...${NC}"
        apt-get install -y whois
    fi

    # Installation des autres outils
    install_nikto
    install_wpscan
    install_sqlmap
}


